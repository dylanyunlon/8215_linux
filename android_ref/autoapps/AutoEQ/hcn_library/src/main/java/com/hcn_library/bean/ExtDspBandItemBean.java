package com.hcn_library.bean;

public class ExtDspBandItemBean {
    private int icon;
    private String name;

    public ExtDspBandItemBean(int icon, String name) {
        this.icon = icon;
        this.name = name;
    }

    public int getIcon() {
        return icon;
    }

    public String getName() {
        return name;
    }

    public void setIcon(int icon) {
        this.icon = icon;
    }

    public void seName(String name) {
        this.name = name;
    }
}
