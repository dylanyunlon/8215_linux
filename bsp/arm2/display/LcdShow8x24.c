void DrawBall(UINT32 x, UINT32 y, UINT32 dia)
{
    struct CENTRE
    {
        UINT32 x1;
        UINT32 y1;
    }center;
    int R =(int)dia / 2;
    int i, j;
    
    center.x1 = x + R;
    center.y1 = y + R;
    
    for (i = 0; i < dia; i++)
        for (j = 0; j < dia; j++)
            if ((R - i) * (R - i) + (R - j) * (R - j) <= R * R)
                _PutTft16Bit_240320(x + j, y + i, (U16)(x * x + y * y));
}
