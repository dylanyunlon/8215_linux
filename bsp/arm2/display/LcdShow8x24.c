void LCD_WriteChar(int x, int y, char c)
{
    int idx, i, j;
    int CharCount = sizeof(CharArray) / sizeof(CharArray[0]);

    for (idx = 0; idx < CharCount; idx++)
    {
        if (CharArray[idx] == c)
            break;
    }
    if (idx >= CharCount)	//遇到不支持的字符
    {
        return;
    }
    if (g_EbootLcdWidth == 800)
    {
        //EdbgOutputDebugString("\r\n\t@%s() L:%d\r\n", __FUNCTION__, __LINE__);
        for (i = 0; i < 32; i++)
        {
            for (j = 0; j < 8; j++)
            {
                if (CharBitmap32[idx][i] & (0x80 >> j))
                {
                    _PutTft16Bit_240320(x + j, y + i, fgcolor);
                }
                else
                {
                    //_PutTft16Bit_240320(x+j, y+i, bkcolor);
                }
            }
        }
    }
    else
    {//EdbgOutputDebugString("\r\n\t@%s() L:%d\r\n", __FUNCTION__, __LINE__);
        for (i = 0; i < 16; i++)
        {
            for (j = 0; j < 8; j++)
            {
                if (CharBitmap16[idx][i] & (0x80 >> j))
                {
                    _PutTft16Bit_240320(x + j, y + i, fgcolor);
                }
                else
                {
                    _PutTft16Bit_240320(x + j, y + i, bkcolor);
                }
            }
        }
    }
}

void ProcessBarShow(int x, int y, BOOL flag)
{
    int w, h;
    flag = flag;
    
    for (h = 0; h <= 32; h++)
    {
        for (w = 0; w < 32; w++)
        {
            if (h < 1)
                _PutTft16Bit_240320(x + (w + h), y + h, 0xffff);
            else if (h < 16)
                _PutTft16Bit_240320(x + (w + h), y + h, 0xf81f + w + h);
            else
                _PutTft16Bit_240320(x + (w + 32 - h), y + h, 0xf81f + w + h);
        }
    }
}

