void LCD_WriteString(char* str)
{
    U16 mCharHeight = 17;
    char* p;
    
    if (!enablelcd)
        return;
    g_EbootLcdWidth = 800;
    //EdbgOutputDebugString("\r\n\t@%s() L:%d\r\n", __FUNCTION__, __LINE__);
    if(g_EbootLcdWidth == 800)
        mCharHeight = 33;
    else
        mCharHeight = 17;

    for (p = str; *p != 0; p++)
    {
        if (*p == '\n')		//换行
        {
            curxpos  = SCREENMARGIN;
            curypos += mCharHeight;
        }
        else if (*p == '\b')	//退格
        {
            curxpos -= CHARWIDTH;
        }
        else	//显示字符
        {//EdbgOutputDebugString("\r\n\t@%s() L:%d\r\n",__FUNCTION__,__LINE__);
            LCD_WriteChar(curxpos, curypos, *p);
            curxpos += CHARWIDTH;			
        }
    }
}

