static void DacHw_SetPwmAnaDefaultConfig()
{
    AUDREG_BITS_W(AUD_REG_PWM_CFG3, BIT_STR_HB_ENPWRDET, BIT_NUM_HB_ENPWRDET, 0);
    AUDREG_BITS_W(AUD_REG_PWM_CFG5, BIT_STR_HB_REV0, BIT_NUM_HB_REV0, 0);
    AUDREG_BITS_W(AUD_REG_PWM_CFG8, BIT_STR_AUD_PWMDAC_REV0, BIT_NUM_AUD_PWMDAC_REV0, 0);
    AUDREG_BITS_W(AUD_REG_PWM_CFG8, BIT_STR_AUD_PWMDAC_REV1, BIT_NUM_AUD_PWMDAC_REV1, 0);
    AUDREG_BITS_W(AUD_REG_PWM_CFG2, BIT_STR_HB_DFC_CH, BIT_NUM_HB_DFC_CH, 0);
}


static void DacHw_SetPwmAnaApllDomain(AUD_PWM_DAC_ID ePwmChId)
{
    AUDREG_BITS_W(AUD_REG_PWM_CFG0, (BIT_STR_HB_CLK_294M_SEL + ePwmChId * 2), BIT_NUM_PWM_2CH_CTL, (AUD_DEF_PWMCLK * 3));

    AUDREG_BITS_W(AUD_REG_PWM_CFG1, (BIT_STR_HB_PS_CLK_294M_SEL + ePwmChId * 2), BIT_NUM_PWM_2CH_CTL, (AUD_DEF_PWMCLK * 3));
}


static VOID DacHw_SetPwmAnaGpioFun(AUD_PWM_DAC_ID ePwmChId, BOOL fgEn)
{
    BOOL fgAnalogFun =  fgEn ? PWM_GPIO_FUNCTION : PWM_ANALOG_FUNCTON;
    BOOL fgGPO = fgEn ? PWM_GPO_EN : PWM_GPI_EN;

    AUDREG_BITS_W(AUD_REG_PWM_CFG10, (BIT_STR_HB_HIZ + ePwmChId * 2), BIT_NUM_PWM_2CH_CTL, (fgEn * 3));
    AUDREG_BITS_W(AUD_REG_PWM_CFG7,  (BIT_STR_GPIO_PWM_G + ePwmChId * 2), BIT_NUM_PWM_2CH_CTL, (fgAnalogFun * 3));
    AUDREG_BITS_W(AUD_REG_PWM_CFG5,  (BIT_STR_GPIO_PWM_EN + ePwmChId * 2), BIT_NUM_PWM_2CH_CTL, (fgGPO * 3));
}


static void DacHw_SetPwmAnaVcmEn(BOOL fgEn)
{
    AUDREG_BITS_W(AUD_REG_PWM_CFG9, BIT_STR_ADAC_VCM_EN, BIT_NUM_ADAC_VCM_EN, fgEn);
}


static void DacHw_SetPwmAnaChEn(AUD_PWM_DAC_ID ePwmChId, BOOL fgEn)
{
    AUDREG_BITS_W(AUD_REG_PWM_CFG2, BIT_STR_HB_ENVO_CH(ePwmChId), BIT_NUM_HB_ENVO_CH, fgEn);
}


static void DacHw_SetPwmAnalogPartStart()
{
    AUD_PWM_DAC_ID i;

    for (i = PWM_SET0; i < _ePwmEndIdx; i++)
    {
        DacHw_SetPwmAnaApllDomain(i);
        DacHw_SetPwmAnaGpioFun(i, FALSE);
    }

    for (i = PWM_SET0; i < _ePwmEndIdx; i++)
    {
        DacHw_SetPwmAnaChEn(i, TRUE);
    }
}


static void DacHw_SetPwmAnalogPartStop()
{
    AUD_PWM_DAC_ID i;
    
    for (i = PWM_SET0; i < _ePwmEndIdx; i++)
    {
        DacHw_SetPwmAnaChEn(i, FALSE);
    }
}


