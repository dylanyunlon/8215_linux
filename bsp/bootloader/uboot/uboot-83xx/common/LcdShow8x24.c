void ProcessBarShow(int x, int y, BOOL flag)
{
    int w, h;
    flag = flag;

    for (h = 0; h <= 32; h++)
    {
        for (w = 0; w < 32; w++)
        {
            if (h < 1)
                _PutTft16Bit_240320(x + (w + h), y + h, 0xffff);
            else if (h < 16)
                _PutTft16Bit_240320(x + (w + h), y + h, 0xf81f + w + h);
            else
                _PutTft16Bit_240320(x + (w + 32 - h), y + h, 0xf81f + w + h);
        }
    }
}

