static BOOL GetBitmapInfo(void* lpMrf, DWORD dwID, BITMAPOBJINFO *pInfo)
{
    BITMAPOBJINFO   *pBitmapInfo;
    MRFHEADER       *pMrfHeader = (MRFHEADER *)lpMrf;

    pBitmapInfo = (BITMAPOBJINFO *)((BYTE *)lpMrf + pMrfHeader->u4OffsetData);

    do
	{
        if (pBitmapInfo->u4FileID == dwID)
        {
            memcpy(pInfo, pBitmapInfo, sizeof(BITMAPOBJINFO));
            return TRUE;
        }
        pBitmapInfo = (BITMAPOBJINFO *)((BYTE *)lpMrf + pBitmapInfo->u4OffsetNextImage);
    }while (pBitmapInfo != lpMrf);

    return FALSE;
}


