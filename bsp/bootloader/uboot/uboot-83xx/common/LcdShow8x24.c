void LCD_DrawProcess(){
	int offsetx = SCREENMARGIN + 60;
	int offsety = SCREENMARGIN_Y + 160;
	int r = number / 2;
	int cx = number / 2;
	int cy = number / 2;
	int x = 0;
	int y = r;
	int delta = 2*(1-r);
	int delta1,delta2,direction;

	for(x = 0; x < number; x++){
		for(y = 0; y < number; y++){
			circle[x][y] = '0';
		}
	}
	x = 0;
	y = r;
	while(y >= 0){
		circle[cx + x][cy + y] = '1';
		circle[cx - x][cy + y] = '1';
		circle[cx + x][cy - y] = '1';
		circle[cx - x][cy - y] = '1';
		if(delta < 0){
			delta1 = 2 * (delta + y) - 1;
			if(delta1 <= 0)
				direction = 1;
			else
				direction = 2;
		} else if(delta > 0){
			delta2 = 2 * (delta - x) - 1;
			if(delta2 <= 0)
				direction=2;
			else
				direction=3;
		} else
			direction = 3;

		switch(direction){
			case 1:
				x++;
				delta += 2 * x + 1;
				break;
			case 2:
				x++;
				y--;
				delta += 2 * (x - y + 1);
				break;
			case 3:
				y--;
				delta += -2 * y + 1;
				break;
		}

	}

	for(y = 0; y < number; y++){
		for(x = 0; x <= number / 2; x++){
			if(circle[x][y] == '0'){
 				//_PutTft16Bit_240320(x + offsetx, y + offsety, bkcolor);
			}else{
 				_PutTft16Bit_240320(x + offsetx, y + offsety, fgcolor);
			}
		}
	}
	for(x = number / 2; x <= processlength - number / 2; x++){
 		_PutTft16Bit_240320(offsetx + x, offsety, fgcolor);
		for(y = 1; y < number - 1; y++){
 			//_PutTft16Bit_240320(offsetx + x, offsety + y, bkcolor);
		}
 		_PutTft16Bit_240320(offsetx + x, offsety + number - 1, fgcolor);
	}
	for(y = 0; y < number; y++){
		for(x = number - 1; x >= number / 2; x--){
			if(circle[x][y] == '0'){
 				//_PutTft16Bit_240320(x + offsetx + processlength - number, y + offsety, bkcolor);
			}else{
 				_PutTft16Bit_240320(x + offsetx + processlength - number, y + offsety, fgcolor);
			}
		}
	}
}

