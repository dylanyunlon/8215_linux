#!/usr/bin/env python3
"""Generate lvgl/lvgl_app/screens/music_pinyin_table.c: pinyin-initial bitmasks for GB2312 hanzi (6763).
   Heteronyms keep ALL initials (e.g. 乐 -> l,y), so a query matches under any reading.
   needs: pip install pypinyin      usage: tools/gen_pinyin_table.py [out.c]"""
import sys
from pypinyin import pinyin, Style
out = sys.argv[1] if len(sys.argv) > 1 else "lvgl/lvgl_app/screens/music_pinyin_table.c"
cps = []
for hi in range(0xB0, 0xF8):
    for lo in range(0xA1, 0xFF):
        try: cps.append(ord(bytes([hi, lo]).decode("gb2312")))
        except UnicodeDecodeError: pass
cps = sorted(set(cps))
rows = []
for cp in cps:
    mask = 0
    for r in pinyin(chr(cp), style=Style.FIRST_LETTER, heteronym=True, errors="ignore")[0]:
        if r and "a" <= r[0] <= "z": mask |= 1 << (ord(r[0]) - 97)
    if mask: rows.append((cp, mask))
with open(out, "w") as f:
    f.write("/* GENERATED by tools/gen_pinyin_table.py - do not edit. %d hanzi, pinyin initials incl. heteronyms. */\n" % len(rows))
    f.write("#include <stdint.h>\n#include <stddef.h>\n\n")
    f.write("const uint16_t music_pinyin_cp[] = {\n")
    for i in range(0, len(rows), 12): f.write("    " + ",".join("0x%04x" % r[0] for r in rows[i:i+12]) + ",\n")
    f.write("};\nconst uint32_t music_pinyin_mask[] = {\n")
    for i in range(0, len(rows), 8): f.write("    " + ",".join("0x%07x" % r[1] for r in rows[i:i+8]) + ",\n")
    f.write("};\nconst size_t music_pinyin_count = %d;\n" % len(rows))
print("wrote", out, len(rows), "hanzi")
